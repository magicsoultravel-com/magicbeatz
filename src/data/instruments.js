/**
 * Built-in sampled sound catalog.
 *
 * Plain data module (not JSON) so it imports directly in every environment.
 * Every pitched sound is backed by a real sample source from smplr:
 *   splendid | soundfont | electricPiano | smolken | mellotron
 * Drum kits are complete sample machines, not individual synth voices.
 *
 * `kind`: 'drum' | 'pitched'
 * `targets`: subset of ['drum','note','chord'].
 * `source`: smplr factory descriptor (see src/audio/sampler.js).
 */

const targets = ['note', 'chord'];
const melody = (id, label, category, instrument, aliases = [], tags = []) => ({
  id,
  kind: 'pitched',
  label,
  category,
  engine: 'sample',
  targets,
  sample: true,
  source: { type: 'soundfont', instrument },
  aliases,
  tags,
});

const electric = (id, label, instrument, aliases = []) => ({
  id,
  kind: 'pitched',
  label,
  category: 'Piano / Keys',
  engine: 'sample',
  targets,
  sample: true,
  source: { type: 'electricPiano', instrument },
  aliases,
  tags: ['electric piano', 'keys', 'vintage'],
});

const tape = (id, label, instrument, tags = []) => ({
  id,
  kind: 'pitched',
  label,
  category: 'Tape / Mellotron',
  engine: 'sample',
  targets,
  sample: true,
  source: { type: 'mellotron', instrument },
  aliases: [],
  tags: ['tape', 'vintage', 'mellotron', ...tags],
});

